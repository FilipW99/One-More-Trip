/**
 * Writes docs/PLACEHOLDERS.md: every placeholder record in the content pack, where it
 * is defined, and which design-doc slot it stands in for. Run after changing content:
 *
 *   npm run placeholders          # rewrite docs/PLACEHOLDERS.md
 *   npm run placeholders -- --check   # exit 1 if the file is out of date (for CI)
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ASSET_FILES } from '../src/content/assets';
import { C } from '../src/content';
import type { Placeholder } from '../src/content/types';

const root = join(import.meta.dirname, '..');
const contentDir = join(root, 'src/content');
const sources = Object.fromEntries(
  readdirSync(contentDir)
    .filter((f) => f.endsWith('.ts'))
    .map((f) => [f, readFileSync(join(contentDir, f), 'utf8').split('\n')]),
);

/** Find `file:line` for a record id (first literal occurrence), else just the file. */
function where(file: string, id: string): string {
  const lines = sources[file];
  const i = lines.findIndex((l) => l.includes(`'${id}'`));
  return i >= 0 ? `src/content/${file}:${i + 1}` : `src/content/${file} (generated)`;
}

interface Row {
  id: string;
  name: string;
  ph: Placeholder;
  at: string;
  art?: string;
}

function rows<T extends { id: string; name?: string; ph: Placeholder | null }>(list: readonly T[], file: string, art?: (r: T) => string): Row[] {
  return list
    .filter((r) => r.ph)
    .map((r) => ({ id: r.id, name: r.name ?? r.id, ph: r.ph!, at: where(file, r.id), art: art?.(r) }));
}

const esc = (s: string) => s.replace(/\|/g, '\\|');

function table(title: string, intro: string, list: Row[]): string {
  if (!list.length) return '';
  const art = list.some((r) => r.art);
  const head = art ? '| Id | Placeholder name | Stands in for | Doc | Defined at | Art key |\n|---|---|---|---|---|---|' : '| Id | Placeholder name | Stands in for | Doc | Defined at |\n|---|---|---|---|---|';
  const body = list
    .map((r) => `| \`${r.id}\` | ${esc(r.name)} | ${esc(r.ph.slot)} | ${r.ph.plan} | \`${r.at}\` |${art ? ` ${r.art ? `\`${r.art}\`` : ''} |` : ''}`)
    .join('\n');
  return `## ${title} (${list.length})\n\n${intro}\n\n${head}\n${body}\n`;
}

const termRows: Row[] = Object.entries(C.termPlaceholders).map(([k, p]) => {
  const i = sources['terms.ts'].findIndex((l) => l.trim().startsWith(`${k}:`));
  return { id: k, name: C.terms[k as keyof typeof C.terms], ph: p!, at: i >= 0 ? `src/content/terms.ts:${i + 1}` : 'src/content/terms.ts' };
});

const sections: [string, string, Row[]][] = [
  ['System names', 'Player-facing names for whole systems. Change them in one place and every screen updates.', termRows],
  ['Acts and locations', 'Act settings for the route (design doc §3.1). Each act lists its monsters, bosses, drop pool and theme colours.', [...rows(C.acts, 'acts.ts', (a) => `tile:${a.id}:floor / tile:${a.id}:wall`), ...rows(C.routes, 'acts.ts')]],
  ['Bosses', 'Boss encounters, with phases, telegraphed attacks and unique tables.', rows(C.bosses, 'bosses.ts', (b) => `monster:${b.asset ?? b.id}`)],
  ['Monsters', 'Regular and elite monsters for each act.', rows(C.monsters.filter((m) => !C.isBoss(m.id)), 'monsters.ts', (m) => `monster:${m.asset ?? m.id}`)],
  ['Slayer masters', 'Task givers met along each route.', rows(C.slayerMasters, 'acts.ts')],
  ['Items', 'Weapons, armour, supplies and boss uniques. Generated tiers (metals, woods) are listed by id; edit the generator tables at the top of items.ts.', rows(C.items, 'items.ts', (i) => `item:${i.asset ?? i.id}`)],
  ['Starting kits', 'Kits for each combat focus (design doc §2).', C.kits.filter((k) => k.ph).map((k) => ({ id: k.focus, name: `${k.focus} kit`, ph: k.ph!, at: where('hub.ts', k.focus) }))],
  ['Prayers, spellbooks and spells', 'Protection and boost prayers, the two spellbooks and their spells.', [...rows(C.prayers, 'prayers.ts', (p) => `prayer:${p.id}`), ...rows(C.spellbooks, 'prayers.ts'), ...rows(C.spells, 'prayers.ts')]],
  ['Relics, Omens and Boons', 'Meta-progression powers (design doc §7).', [...rows(C.relics, 'powers.ts'), ...rows(C.omens, 'powers.ts'), ...rows(C.boons, 'powers.ts')]],
  ['Hub rooms', 'Hub features and their tiers (design doc §6).', rows(C.hub, 'hub.ts')],
  ['Pets', 'Boss pets (design doc §7.3).', rows(C.pets, 'hub.ts', (p) => `pet:${p.id}`)],
  ['Skills', 'Skill tracks whose names come from the source game (design doc §4.4).', rows(C.skills, 'skills.ts', (s) => `skill:${s.id}`)],
];

const total = sections.reduce((n, [, , r]) => n + r.length, 0);
const overrides = Object.keys(ASSET_FILES).length;

const out = `# Placeholder content

<!-- Generated by \`npm run placeholders\` (scripts/placeholder-report.ts). Do not edit by hand. -->

This build ships with **generic placeholders for all content the design doc takes from the source game**: bosses, places, monsters, items, prayers, spells, relics, pets, system names and all art. Nothing here is imported or recreated from the source game. Every placeholder record carries a \`ph\` tag naming the design-doc slot it fills, and the game shows a purple **PH** badge next to it (toggle in Settings).

- **${total} placeholder records** across ${sections.filter(([, , r]) => r.length).length} groups, listed below.
- **Art:** every image is a procedural placeholder drawn by \`src/render/placeholders.ts\`. ${overrides} art override${overrides === 1 ? '' : 's'} mapped in \`src/content/assets.ts\`; more can go in \`public/assets/manifest.json\`.
- **How to replace:** see [REPLACING_CONTENT.md](REPLACING_CONTENT.md).

Records with \`ph: null\` are original to this game (for example most Boons, Tasks and gathering rooms) and need no replacement.

${sections.map(([t, i, r]) => table(t, i, r)).filter(Boolean).join('\n')}
## Art keys

Every visual is looked up by key. With no file mapped, a procedural shape is drawn.

| Key pattern | Used for | Count |
|---|---|---|
| \`item:<itemId>\` | Inventory, equipment and loot icons | ${C.items.length} |
| \`monster:<monsterId>\` | Monster and boss sprites (64 px per tile of size) | ${C.monsters.length} |
| \`player:<focus>\` | Player sprite for melee, ranged and magic | 3 |
| \`pet:<petId>\` | Pet sprites | ${C.pets.length} |
| \`tile:<actId>:floor\`, \`tile:<actId>:wall\` | Arena tiles per act | ${C.acts.length * 2} |
| \`prayer:<prayerId>\` | Prayer icons | ${C.prayers.length} |
| \`skill:<skillId>\` | Skill icons | ${C.skills.length} |
`;

const target = join(root, 'docs/PLACEHOLDERS.md');
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing
  }
  if (current !== out) {
    console.error('docs/PLACEHOLDERS.md is out of date. Run `npm run placeholders`.');
    process.exit(1);
  }
  console.log(`docs/PLACEHOLDERS.md is up to date (${total} placeholders).`);
} else {
  writeFileSync(target, out);
  console.log(`Wrote docs/PLACEHOLDERS.md (${total} placeholders).`);
}
